// Проверка ответа модели: диагнозы и лекарства недопустимы
const OUT_BAD = [
  /у(вас|тебя) (депрессия|тревожное расстройство|птср|биполярн\w+|шизофрения|расстройство личности)/,
  /принимайте (антидепрессант|препарат|лекарств|таблет)/,
  /\d+\s?(мг|миллиграмм)/,
];
const OUT_FALLBACK =
  "Я не могу оценивать состояние или советовать лекарства: для этого нужен врач или психолог. " +
  "Зато могу помочь разобраться в мыслях. Что сейчас для вас самое трудное?";

function stripThink(t) {
  return t
    .replace(/^<think>[\s\S]*?(<\/think>|$)/, "")
    .replace(/^[\s\S]*?<\/think>/, "")
    .trim();
}

// Убирает разметку и обрезает недописанное предложение
function tidy(text) {
  let t = text.replace(/[*_#`]+/g, "").replace(/^\s*[-•]\s+/gm, "").trim();
  if (t && !/[.!?…»")]$/.test(t)) {
    const cut = Math.max(t.lastIndexOf("."), t.lastIndexOf("!"), t.lastIndexOf("?"));
    if (cut > t.length * 0.4) t = t.slice(0, cut + 1);
  }
  return t;
}

function guard(text) {
  return any(OUT_BAD, norm(text)) ? OUT_FALLBACK : text;
}

/* ---------- 6. Простой режим (без нейросети) ---------- */
const SIMPLE_Q = [
  ["Расскажите чуть подробнее, что именно происходит?", "Что в этой ситуации для вас самое трудное?"],
  ["Чего вам хотелось бы, чтобы стало иначе?", "Как бы выглядела ситуация, которая вас устроила бы?"],
  ["Что вы уже пробовали, и что из этого хоть немного помогало?", "Что сейчас мешает больше всего?"],
  ["Какие варианты вы видите сами, даже неидеальные?", "Что бы вы посоветовали близкому другу в такой ситуации?"],
  ["Какой один маленький шаг вы могли бы сделать в ближайшие сутки?", "Когда и как именно вы его сделаете?"],
];
const SIMPLE_REFLECT = ["Я вас слышу.", "Спасибо, что делитесь этим.", "Кажется, для вас это значимо."];
const SIMPLE_BYE =
  "Спасибо за разговор. Помните про свой маленький шаг. Вы можете вернуться сюда в любой момент.";

/* ============================================================
   Класс Coach
   ============================================================ */
export class Coach {
  constructor() {
    this.mode = null;      // "ai" — нейросеть, "simple" — простой режим
    this.engine = null;
    this.history = [];
    this.turns = 0;
    this.care = false;     // после тревожного сигнала разговор ведётся бережнее
  }

  greeting() {
    return "Здравствуйте. Я рад, что вы зашли. Здесь можно говорить в своём темпе. Что сейчас занимает ваши мысли?";
  }

  reset() {
    this.history = [];
    this.turns = 0;
    this.care = false;
  }

  /* ---------- 5. Запуск ---------- */
  async start(onProgress) {
    const simple = (reason) => { this.mode = "simple"; return { mode: "simple", reason }; };

    let gpu = false;
    try { gpu = !!(navigator.gpu && (await navigator.gpu.requestAdapter())); } catch (e) {}
    if (!gpu) return simple("Ваше устройство или браузер не поддерживают запуск нейросети.");

    let webllm;
    try {
      webllm = await import(WEBLLM_URL);
    } catch (e) {
      return simple(navigator.onLine
        ? "Не удалось загрузить файлы нейросети."
        : "Вы без интернета, а нейросеть ещё ни разу не загружалась.");
    }

    const models = webllm.prebuiltAppConfig.model_list
      .filter((m) => MODEL_FILTER.test(m.model_id))
      .sort((a, b) => (a.vram_required_MB || 0) - (b.vram_required_MB || 0));
    if (!models.length) return simple("Не удалось найти подходящую нейросеть.");

    try {
      onProgress && onProgress(0);
      this.engine = await webllm.CreateMLCEngine(models[0].model_id, {
        initProgressCallback: (p) => onProgress && onProgress(Math.round((p.progress || 0) * 100)),
      });
      this.mode = "ai";
      return { mode: "ai" };
    } catch (e) {
      this.engine = null;
      return simple("Не удалось запустить нейросеть: " + (e && e.message ? e.message : e) + ".");
    }
  }

  /* ---------- Ответ ---------- */
  // Возвращает { kind: "bot" | "safe", text, note? }
  async reply(userText, onText, signal) {
    const t = norm(userText);

    // Острый кризис: без нейросети, только заготовленный текст
    if (any(CRISIS_ACUTE, t)) {
      this.care = true;
      return { kind: "safe", text: CRISIS_TEXT };
    }
    const watch = any(CRISIS_WATCH, t);
    if (watch) this.care = true;
    if (watch && this.mode === "simple") return { kind: "safe", text: WATCH_TEXT_SIMPLE };

    this.turns += 1;
    this.history.push({ role: "user", content: userText });

    const stage = stageFor(this.turns);
    const emotion = detectEmotion(t);
    let out = "";
    try {
      out = this.mode === "ai"
        ? await this._askModel(t, stage, emotion, watch, onText, signal)
        : await this._askSimple(t, stage, emotion, onText, signal);
    } catch (e) {
      this.history.pop();
      this.turns -= 1;
      throw e;
    }

    out = guard(tidy(out));
    if (!out) {
      this.history.pop();
      this.turns -= 1;
      throw new Error("пустой ответ");
    }
    this.history.push({ role: "assistant", content: out });
    return { kind: "bot", text: out, note: watch ? WATCH_NOTE : null };
  }

  _hints(t, stage, emotion, watch) {
    const h = ["Этап разговора: " + stage.name + ". " + stage.hint];
    if (emotion) h.push(emotion.hint);
    if (ADVICE.test(t)) h.push("Человек просит совет. Предложи 2–3 варианта на выбор и подчеркни, что решает он сам.");
    if (t.trim().length < 12 || SHORT.test(t.trim())) {
      h.push("Ответ человека совсем короткий, ему может быть трудно говорить. Не дави: задай очень простой вопрос или предложи выбор из двух вариантов.");
    }
    if (BYE.test(t.trim())) h.push("Человек благодарит или прощается. Тепло подведи итог, напомни о его шаге и не задавай новых вопросов.");
    if (watch) h.push("Человек упоминает возможную опасность или самоповреждение. Не продолжай коучинг: выскажи заботу, спроси, в безопасности ли он сейчас, и предложи живую помощь.");
    else if (this.care) h.push("Ранее в разговоре прозвучал тревожный сигнал. Будь особенно бережным и в конце мягко напомни, что живая помощь доступна.");
    return h;
  }

  async _askModel(t, stage, emotion, watch, onText, signal) {
    const system = BASE_PROMPT + "\n\nПодсказки для следующего ответа (человеку их не показывай):\n- " +
      this._hints(t, stage, emotion, watch).join("\n- ");
    const stream = await this.engine.chat.completions.create({
      messages: [{ role: "system", content: system }, ...this.history.slice(-8)],
      stream: true, temperature: 0.6, top_p: 0.9, max_tokens: 1500,
    });
    let full = "";
    for await (const chunk of stream) {
      if (signal && signal.aborted) { this.engine.interruptGenerate(); break; }
      full += chunk.choices[0]?.delta?.content || "";
      onText && onText(stripThink(full));
    }
    return stripThink(full);
  }

  async _askSimple(t, stage, emotion, onText, signal) {
    let text;
    if (BYE.test(t.trim())) {
      text = SIMPLE_BYE;
    } else {
      const i = STAGES.indexOf(stage);
      const reflect = emotion ? emotion.say : SIMPLE_REFLECT[this.turns % SIMPLE_REFLECT.length];
      const q = SIMPLE_Q[i][this.turns % 2];
      text = reflect + " " + q;
    }
    let out = "";
    for (const ch of text) {
      if (signal && signal.aborted) break;
      await sleep(10);
      out += ch;
      onText && onText(out);
    }
    return out;
  }
}